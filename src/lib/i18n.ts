export function parseLocale(value: string | undefined | null): Locale {
  return value === "bn" ? "bn" : "en";
}

export function translate(locale: Locale, message: string, values?: Record<string, string | number>): string {
  const translated = locale === "bn" ? bengaliMessages[message] ?? message : message;
  if (!values) return translated;
  return Object.entries(values).reduce((result, [key, value]) => result.replaceAll(`{${key}}`, String(value)), translated);
}

export function intlLocale(locale: Locale) {
  return locale === "bn" ? "bn-BD" : "en-BD";
}

export function formatDate(locale: Locale, date: Date, options: Intl.DateTimeFormatOptions) {
  return new Intl.DateTimeFormat(intlLocale(locale), options).format(date);
}

export function formatNumber(locale: Locale, value: number, options?: Intl.NumberFormatOptions) {
  return new Intl.NumberFormat(intlLocale(locale), options).format(value);
}
